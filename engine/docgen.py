"""
Generates docs from the component registry so they can never drift from the code:

    python -m engine.docgen
      -> docs/COMPONENTS.md          human reference
      -> docs/storyboard.schema.json JSON-Schema (validate / constrain LLM output)
      -> docs/LLM_SYSTEM_PROMPT.md   paste into the LLM that writes your storyboard JSON
"""

import json
import re
import typing
from pathlib import Path

from engine.registry import load_components
from engine.theme import COLOR_NAMES, THEMES

DOCS = Path(__file__).resolve().parent.parent / "docs"


def _type_str(ann) -> str:
    s = str(ann).replace("typing.", "")
    s = re.sub(r"<class '([\w.]+)'>", lambda m: m.group(1).split(".")[-1], s)
    s = re.sub(r"engine\.[\w.]+\.(\w+)", r"\1", s)
    return s.replace("NoneType", "null")


def field_rows(spec):
    rows = []
    skip = {"component_type", "exact_time"}
    for name, f in spec.model_fields.items():
        if name in skip:
            continue
        default = "required" if f.is_required() else repr(f.get_default(call_default_factory=True)) if f.default_factory else repr(f.default)
        if len(default) > 40:
            default = "(list)"
        rows.append((name, _type_str(f.annotation), default))
    return rows


def build_components_md(reg) -> str:
    out = ["# Component reference\n", "Auto-generated by `python -m engine.docgen`. Every component also accepts `heading`, `subheading`, "
           "`trigger_keyword`. Items inside lists accept `trigger_keyword` too (the item appears the moment that word is spoken).\n"]
    out.append(f"**Colours** (`color_theme` / `theme_color`): {', '.join(COLOR_NAMES)}\n")
    for name in sorted(reg):
        c = reg[name]
        out.append(f"\n## {name}\n\n{c.description}\n\n**Best for:** {c.best_for}\n\n| field | type | default |\n|---|---|---|")
        for n, t, d in field_rows(c.Spec):
            out.append(f"| `{n}` | `{t}` | {d} |")
        out.append("\n```json\n" + json.dumps(c.example, indent=2, ensure_ascii=False) + "\n```")
    return "\n".join(out) + "\n"


def build_schema(reg) -> dict:
    defs, variants = {}, []
    for name, c in sorted(reg.items()):
        s = c.Spec.model_json_schema(ref_template="#/$defs/{model}")
        for k, v in s.pop("$defs", {}).items():
            defs[k] = v
        variants.append(s)
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "VideoStoryboard", "type": "object", "required": ["scenes"],
        "properties": {
            "title": {"type": "string"},
            "aspect_ratio": {"enum": ["16:9", "9:16", "1:1"]},
            "studio_theme": {"enum": list(THEMES)},
            "fps": {"type": "integer", "default": 30},
            "captions": {"enum": ["off", "pop", "line"]},
            "background": {"enum": ["grid", "plain", "spotlight_only"]},
            "scenes": {"type": "array", "items": {
                "type": "object", "required": ["scene_id", "narration_text", "visual"],
                "properties": {
                    "scene_id": {"type": "string"}, "narration_text": {"type": "string"},
                    "transition": {"enum": ["fade", "slide", "zoom", "wipe", "cut"]},
                    "camera": {"enum": ["static", "push_in", "pull_out", "drift"]},
                    "visual": {"oneOf": variants}}}}},
        "$defs": defs,
    }


def build_prompt(reg) -> str:
    cat = []
    for name in sorted(reg):
        c = reg[name]
        cat.append(f"### {name}\nUse for: {c.best_for}\nExample:\n```json\n{json.dumps(c.example, ensure_ascii=False)}\n```\n"
                   f"Narration that fits it: \"{c.example_narration}\"\n")
    return f"""# SYSTEM PROMPT - storyboard writer

You write ONE JSON file that a video engine turns into a finished video. The human will record the voiceover from your
`narration_text` and render. You never write timestamps: the engine finds every scene and every reveal in the audio.

## Output rules
1. Output ONLY valid JSON (no markdown fences, no comments).
2. Top level: `title`, `aspect_ratio` ("9:16" for Shorts/Reels/TikTok, "16:9" for YouTube, "1:1" for feeds), `studio_theme`
   (one of: {', '.join(THEMES)}), `captions` ("pop" word-highlight captions, "line", or "off"), `scenes`.
3. Each scene: `scene_id` (unique snake_case), `narration_text` (exactly what will be spoken, natural sentences, 18-45 words),
   `visual` (one component, see catalogue). Optional: `transition` (fade|slide|zoom|wipe|cut), `camera` (static|push_in|pull_out|drift).
4. `narration_text` of all scenes, concatenated, is the full voiceover script. Write it as spoken language, no stage directions,
   spell out symbols that must be said aloud ("fifty five percent").
5. Every `trigger_keyword` MUST be a word or short phrase that appears verbatim in THAT scene's `narration_text`, in the order the
   items should appear. The item pops up exactly when the word is spoken. Give every list item/bar/card/step a trigger_keyword.
6. Open with a hook scene (KineticText, HeroQuoteHook, RetroCrashDialog or TitleCard); close with CallToAction or TitleCard.
7. Vary components: never use the same component_type twice in a row. Match component to content using "Use for".
8. Keep on-screen text short (titles <= 4 words, details <= 8 words). The narration carries the detail.
9. Colours: {', '.join(COLOR_NAMES)}. Icons: any Lucide icon name (e.g. "database", "shield-check", "rocket") or brand slug
   (e.g. "docker", "kubernetes", "postgresql", "python", "github"). Unknown names fall back to a generic glyph.
10. Targets: 9:16 videos 25-60 s => 5-9 scenes; 16:9 videos 3-8 min => 15-40 scenes.

## Component catalogue
{chr(10).join(cat)}
"""


def main():
    reg = load_components()
    DOCS.mkdir(exist_ok=True)
    (DOCS / "COMPONENTS.md").write_text(build_components_md(reg), encoding="utf-8")
    (DOCS / "storyboard.schema.json").write_text(json.dumps(build_schema(reg), indent=2), encoding="utf-8")
    (DOCS / "LLM_SYSTEM_PROMPT.md").write_text(build_prompt(reg), encoding="utf-8")
    print(f"wrote docs for {len(reg)} components -> {DOCS}")


if __name__ == "__main__":
    main()
